/**
 * Variable (level-adaptive) error diffusion.
 *
 * A fixed kernel spreads a pixel's error the same way whatever the pixel was, which is why
 * Floyd-Steinberg leaves worms and tails in near-white and near-black areas: the few dots there
 * line up into structures the eye picks out. Ostromoukhov's method varies the three weights with
 * the input level instead, from a table tuned so that the dot pattern stays unstructured all the
 * way to the ends of the range. Zhou and Fang extend it with a randomised threshold, which breaks
 * up the remaining regular patterns at the cost of a little noise.
 *
 * Both spread the error to three neighbours only: the next pixel, and the two below it on the
 * side the scan came from. That makes them cheaper than Stucki or Jarvis, not dearer.
 *
 * Tables from libdither (https://github.com/robertkist/libdither) by Robert Kist, whose licence
 * notice travels with the tables in js/dither_tables.js. Weights are pre-divided here, so each
 * row sums to 1.
 *
 * V. Ostromoukhov, "A simple and efficient error-diffusion algorithm", SIGGRAPH 2001.
 * B. Zhou and X. Fang, "Improving mid-tone quality of variable-coefficient error diffusion
 * using threshold modulation", SIGGRAPH 2003.
 */


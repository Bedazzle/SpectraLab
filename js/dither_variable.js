/** The variable kernels, offered next to the fixed ones in the Kernel picker. */
const VARIABLE_ED_KERNELS = {
  ostromoukhov: { label: 'Ostromoukhov', randomised: false },
  zhoufang: { label: 'Zhou-Fang', randomised: true }
};

/** Where the error goes, forward scan: next pixel, below-behind, below. */
const VARIABLE_ED_OFFSETS = [[1, 0], [-1, 1], [0, 1]];

/**
 * The three weights for a pixel at this level.
 * @param {number} level - the pixel's own level, 0 = paper, 1 = ink
 * @param {string} type - 'ostromoukhov' or 'zhoufang'
 * @returns {number[]} [next, below-behind, below], summing to 1
 */
function variableEdWeights(level, type) {
  let t = level;
  if (t < 0) t = 0; else if (t > 1) t = 1;
  if (type === 'zhoufang') {
    // levels above mid grey behave like their complement
    if (t > 0.5) t = 1 - t;
    let i = Math.round(t * 255);
    if (i > 127) i = 127;
    return ZHOUFANG_WEIGHTS[i];
  }
  return OSTROMOUKHOV_WEIGHTS[Math.round(t * 255)];
}

/**
 * Zhou-Fang's modulated threshold for a pixel, in place of a flat 0.5. Needs a generator
 * rather than Math.random so that a preview redrawn with the same settings comes out the same.
 * @param {number} level - the pixel's own level, 0 = paper, 1 = ink
 * @param {function(): number} rng - returns a number in 0..1
 * @returns {number} threshold in 0..1
 */
function zhouFangThreshold(level, rng) {
  let t = level;
  if (t < 0) t = 0; else if (t > 1) t = 1;
  if (t > 0.5) t = 1 - t;
  let i = Math.round(t * 255);
  if (i > 127) i = 127;
  return (128 + Math.floor(rng() * 128) * (ZHOUFANG_RAND_SCALE[i] / 100)) / 256;
}

/**
 * Small deterministic generator, so the same picture and settings always dither the same way.
 * @param {number} seed - any integer
 * @returns {function(): number} returns numbers in 0..1
 */
function makeDitherRng(seed) {
  let s = (seed | 0) || 1;
  return function () {
    // xorshift32
    s ^= s << 13; s |= 0;
    s ^= s >>> 17;
    s ^= s << 5; s |= 0;
    return ((s >>> 0) % 100000) / 100000;
  };
}

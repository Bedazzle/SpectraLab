/**
 * Render a threshold matrix as a grey ramp, for the preview swatch next to the picker.
 * @param {DitherMatrix} m - matrix to visualise
 * @param {number} w - target width in pixels
 * @param {number} h - target height in pixels
 * @returns {Uint8Array} w*h bytes, 0 = ink, 255 = paper
 */
function renderMatrixSwatch(m, w, h) {
  const out = new Uint8Array(w * h);
  const rows = m.rows, mh = rows.length, mw = rows[0].length;
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      // Level ramps left to right; a diagonal wobble shows how the tile joins up
      const level = (x + 0.5) / w;
      const threshold = (rows[y % mh][x % mw] + 0.5) / m.divisor;
      out[y * w + x] = level < threshold ? 0 : 255;
    }
  }
  return out;
}

/**
 * Extent of an error diffusion kernel, for drawing it.
 * @param {DitherKernel} k - kernel to measure
 * @returns {{minX: number, maxX: number, maxY: number, maxW: number}} bounds and peak weight
 */
function kernelBounds(k) {
  let minX = 0, maxX = 0, maxY = 0, maxW = 0;
  for (const [dx, dy, w] of k.kernel) {
    if (dx < minX) minX = dx;
    if (dx > maxX) maxX = dx;
    if (dy > maxY) maxY = dy;
    if (w > maxW) maxW = w;
  }
  return { minX, maxX, maxY, maxW };
}
